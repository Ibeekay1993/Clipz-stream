def analyze_face_centers(vpath: str, start_sec: float, end_sec: float, sample_fps: float = 2.0) -> list:
    """Track the most likely active speaker face center for dynamic 9:16 crops."""
    try:
        import cv2
        import numpy as np
        if not os.path.exists(vpath): return []
        cascade_path = cv2.data.haarcascades + 'haarcascade_frontalface_default.xml'
        if not os.path.exists(cascade_path): return []

        face_cascade = cv2.CascadeClassifier(cascade_path)
        cap = cv2.VideoCapture(vpath)
        if not cap.isOpened(): return []

        fps = cap.get(cv2.CAP_PROP_FPS) or 30.0
        width = cap.get(cv2.CAP_PROP_FRAME_WIDTH) or 1920.0

        start_frame = int(start_sec * fps)
        end_frame = int(end_sec * fps)
        frame_step = max(1, int(fps / sample_fps))

        cap.set(cv2.CAP_PROP_POS_FRAMES, start_frame)
        current_frame = start_frame
        points = []
        prev_gray = None
        tracked_x = None

        while current_frame <= end_frame:
            ret, frame = cap.read()
            if not ret: break
            t_rel = (current_frame - start_frame) / fps
            gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)
            faces = face_cascade.detectMultiScale(gray, scaleFactor=1.1, minNeighbors=4, minSize=(60, 60))
            if len(faces) > 0:
                frame_area = float(frame.shape[0] * frame.shape[1])
                best = None
                for x, y, w, h in faces:
                    center_x = (x + w / 2.0) / width
                    size_score = min(1.0, (w * h) / max(1.0, frame_area * 0.12))
                    center_score = 1.0 - min(1.0, abs(center_x - 0.5) * 2.0)
                    continuity_score = 1.0 - min(1.0, abs(center_x - tracked_x) * 3.0) if tracked_x is not None else center_score
                    motion_score = 0.0
                    if prev_gray is not None:
                        mouth_y1 = y + int(h * 0.55)
                        mouth_y2 = min(gray.shape[0], y + h)
                        mouth_x1 = max(0, x)
                        mouth_x2 = min(gray.shape[1], x + w)
                        curr_roi = gray[mouth_y1:mouth_y2, mouth_x1:mouth_x2]
                        prev_roi = prev_gray[mouth_y1:mouth_y2, mouth_x1:mouth_x2]
                        if curr_roi.size and prev_roi.shape == curr_roi.shape:
                            motion_score = min(1.0, float(np.mean(cv2.absdiff(curr_roi, prev_roi))) / 18.0)
                    score_val = (continuity_score * 0.45) + (motion_score * 0.30) + (center_score * 0.15) + (size_score * 0.10)
                    if best is None or score_val > best[0]:
                        best = (score_val, x, y, w, h)
                _, x, y, w, h = best
                center_x_norm = (x + w / 2.0) / width
                tracked_x = center_x_norm
                points.append((t_rel, center_x_norm))
            prev_gray = gray
            current_frame += frame_step
            cap.set(cv2.CAP_PROP_POS_FRAMES, current_frame)
        cap.release()
        return points
    except Exception as e:
        logger.warning(f"OpenCV face tracking error: {e}")
        return []

def build_dynamic_crop_x_expr(points: List[Tuple[float, float]]) -> str:
    """Build dynamic FFmpeg linear interpolation crop x expression from face points"""
    if not points: return "(in_w-out_w)/2"
    smoothed = []
    curr_bin = None
    bin_vals = []
    for t, x_norm in points:
        t_sec = int(t)
        if curr_bin is None: curr_bin = t_sec
        if t_sec == curr_bin:
            bin_vals.append(x_norm)
        else:
            smoothed.append((curr_bin, sum(bin_vals) / len(bin_vals)))
            curr_bin = t_sec
            bin_vals = [x_norm]
    if bin_vals and curr_bin is not None:
        smoothed.append((curr_bin, sum(bin_vals) / len(bin_vals)))
    if not smoothed: return "(in_w-out_w)/2"

    expr_parts = []
    for t_sec, norm_x in smoothed:
        target_x = f"min(max(0,in_w*{norm_x:.3f}-out_w/2),in_w-out_w)"
        expr_parts.append(f"gte(t,{t_sec:.1f}),{target_x}")

    expr = "(in_w-out_w)/2"
    for part in reversed(expr_parts):
        cond, val = part.split(",", 1)
        expr = f"if({cond},{val},{expr})"
    return expr

def transcode_and_upload(src: str, start: float, end: float, out: str, words: List[dict] = None, burn_captions: bool = False) -> str:
    """Safe FFmpeg crop + OpenCV Face-Tracking + ASS Kinetic Subtitles + Supabase CDN Upload"""
    dur = end - start

    # 1. Analyze face positions for dynamic 9:16 speaker tracking
    face_pts = analyze_face_centers(src, start, end)
    crop_x_expr = build_dynamic_crop_x_expr(face_pts)
    logger.info(f"OpenCV Face Tracking generated {len(face_pts)} face samples. Crop X expr: {crop_x_expr[:60]}...")

    # 2. Generate ASS Subtitle File if words provided
    ass_path = out + ".ass"
    use_subtitles = False
    if words and burn_captions:
        try:
            generate_ass_file(words, start, ass_path)
            use_subtitles = os.path.exists(ass_path)
        except Exception as e:
            logger.warning(f"ASS subtitle generation failed: {e}")

    crop_filter = f"scale=ih*9/16:ih:force_original_aspect_ratio=increase,crop=w=ih*9/16:h=ih:x='{crop_x_expr}':y=0,scale=720:1280"
    if use_subtitles:
        escaped_ass = ass_path.replace("\\", "/").replace(":", "\\:")
        vf = f"{crop_filter},subtitles='{escaped_ass}',fps=30"
    else:
        vf = f"{crop_filter},fps=30"

    def run_render(filter_graph: str, label: str):
        cmd = [
            resolve_media_binary("FFMPEG_BINARY", "ffmpeg"), "-y", "-hide_banner", "-loglevel", "error",
            "-ss", str(max(0.0, start - 1.5)), "-i", src, "-ss", str(min(1.5, start)), "-t", str(dur),
            "-vf", filter_graph, "-c:v", "libx264", "-preset", "ultrafast", "-crf", "26",
            "-c:a", "aac", "-b:a", "128k", "-movflags", "+faststart", "-pix_fmt", "yuv420p", out
        ]
        res = subprocess.run(cmd, capture_output=True, text=True)
        if res.returncode != 0:
            raise Exception(f"{label} FFmpeg transcode failed: {res.stderr[-300:] if res.stderr else 'Unknown error'}")
        validate_rendered_mp4(out, max(0.5, min(dur, 1.0)))

    try:
        run_render(vf, "Advanced")
    except Exception as primary_error:
        logger.warning(f"Advanced render failed; retrying basic fallback: {primary_error}")
        try:
            if os.path.exists(out):
                os.remove(out)
        except Exception:
            pass
        fallback_filter = "scale=ih*9/16:ih:force_original_aspect_ratio=increase,crop=w=ih*9/16:h=ih:x=(in_w-out_w)/2:y=0,scale=720:1280,fps=30"
        run_render(fallback_filter, "Fallback")

    if os.path.exists(ass_path):
        try: os.remove(ass_path)
        except: pass

    # Prefer Supabase Storage, but keep the locally generated Modal clip usable.
    fname = os.path.basename(out)
    if supabase:
        try:
            with open(out, 'rb') as f:
                res = supabase.storage.from_("clips").upload(path=fname, file=f, file_options={"content-type": "video/mp4", "upsert": "true"})
                logger.info(f"Supabase upload response: {res}")
            public_url = supabase.storage.from_("clips").get_public_url(fname)
            return public_url
        except Exception as e:
            logger.warning(f"Supabase clip upload failed; serving Modal clip locally: {e}")

    if modal_volume:
        try:
            modal_volume.commit()
        except Exception as ve:
            logger.warning(f"Modal volume commit note after clip transcode: {ve}")
    return f"/clips/{fname}"

