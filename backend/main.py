async def run_pipeline(vpath: str, url_or_name: str, n: int, base: str, job_id: str = None, burn_captions: bool = True) -> dict:
    def update_job(prog: int, step: str):
        if job_id:
            push_job_update(job_id, prog, step)

    update_job(10, "Extracting audio & speech transcription...")
    logger.info("Starting Multi-AI Engine transcript analysis...")
    words = []

    # Fast-Track 1: Try YoutubeTranscriptApi for YouTube links
    if "youtube.com" in url_or_name or "youtu.be" in url_or_name:
        try:
            vid_match = re.search(r'(?:v=|\/)([0-9A-Za-z_-]{11})', url_or_name)
            if vid_match:
                v_id = vid_match.group(1)
                from youtube_transcript_api import YouTubeTranscriptApi
                api = YouTubeTranscriptApi()
                yt_trans = api.fetch(v_id)
                if yt_trans:
                    logger.info(f"YouTubeTranscriptApi fast-track fetched {len(yt_trans)} captions for {v_id}")
                    for item in yt_trans:
                        s_ms = int(item.get('start', 0) * 1000)
                        d_ms = int(item.get('duration', 2.0) * 1000)
                        text_val = item.get('text', '')
                        for w in text_val.split():
                            words.append({"word": w, "startMs": s_ms, "endMs": s_ms + d_ms})
        except Exception as yte:
            logger.warning(f"YouTubeTranscriptApi fast-track note: {yte}")

    if not words:
        try:
            words = transcribe(vpath)
        except Exception as te:
            logger.warning(f"Speech transcription unavailable, falling back to timed clips: {te}")
            words = []

    chunks = semantic_chunks(words) if words else []
    if not chunks:
        logger.info("Generating fail-safe timed chunks...")
        chunks = build_uniform_chunks(vpath, n)
    if not chunks: raise HTTPException(500, "Could not form video segments")

    # Call Orchestrated Multi-AI Microservices Pipeline
    try:
        ai_analysis = orchestrate_multi_ai_pipeline(chunks, n)
    except Exception as ae:
        logger.warning(f"AI clip analysis unavailable, using heuristic chunk scores: {ae}")
        ai_analysis = []
    chosen_chunks = []
    if ai_analysis:
        for la in ai_analysis:
            cid = la.get("chunk_id", 0)
            if 0 <= cid < len(chunks):
                c = chunks[cid]
                c.score = la.get("viralScore", 85)
                c.hook = la.get("hookType", "General")
                c.reasons = [la.get("viralReason", "High-engagement viral hook")]
                c.broll_query = la.get("brollQuery", "")
                c.text = la.get("title", c.title()) # Override title
                chosen_chunks.append((c, la.get("title", c.title())))

    if len(chosen_chunks) < n:
        scored = [score(c) for c in chunks]
        heuristic_chosen = [(c, c.title()) for c in select(scored, n)]
        for hc, htitle in heuristic_chosen:
            if len(chosen_chunks) >= n:
                break
            if not any(cc[0].text == hc.text for cc in chosen_chunks):
                chosen_chunks.append((hc, htitle))

    chosen_chunks = fill_requested_chunks(chosen_chunks, vpath, n)

    update_job(55, "Rendering downloadable MP4 clips...")
    clips_out = [None] * len(chosen_chunks)

    def process_selected_chunk(index_and_tuple):
        i, (chunk, title_text) = index_and_tuple
        fname = f"clip_{uuid.uuid4().hex[:8]}_{i}.mp4"
        fpath = os.path.join(CLIPS_DIR, fname)
        try:
            clip_url = transcode_and_upload(vpath, chunk.start, chunk.end, fpath, words=chunk.words, burn_captions=burn_captions)
            if clip_url.startswith("/clips/"):
                clip_url = f"{base}{clip_url}"

            off = chunk.words[0]["startMs"] if chunk.words else int(chunk.start * 1000)
            captions = [{"word": w["word"], "startMs": w["startMs"] - off, "endMs": w["endMs"] - off} for w in chunk.words]
            return i, {
                "id": i,
                "title": title_text,
                "startSec": int(chunk.start),
                "endSec": int(chunk.end),
                "viralScore": chunk.score or 85,
                "viralReason": chunk.reasons[0] if chunk.reasons else "High-engagement clip",
                "captions": captions,
                "hookType": chunk.hook,
                "durationSec": round(chunk.duration, 1),
                "clipUrl": clip_url,
                "clip_url": clip_url,
                "brollQuery": getattr(chunk, "broll_query", ""),
            }
        except Exception as e:
            logger.error(f"Failed to render selected chunk {i}: {e}")
            return i, None

    with concurrent.futures.ThreadPoolExecutor(max_workers=render_worker_count(len(chosen_chunks))) as executor:
        futures = [executor.submit(process_selected_chunk, item) for item in enumerate(chosen_chunks)]
        for future in concurrent.futures.as_completed(futures):
            idx, rendered = future.result()
            if rendered:
                clips_out[idx] = rendered
                update_job(60 + int(((idx + 1) / max(1, len(chosen_chunks))) * 35), f"Rendered clip {idx + 1} of {len(chosen_chunks)}...")

    clips_out = [c for c in clips_out if c is not None]
    if not clips_out:
        raise Exception("No clips could be rendered into MP4 output.")

    if modal_volume:
        try:
            modal_volume.commit()
            logger.info("Committed modal_volume after all clips transcoded in run_pipeline.")
        except Exception as ve:
            logger.warning(f"Modal volume commit note in run_pipeline: {ve}")

    result = {"url": url_or_name, "duration": words[-1]["endMs"]/1000 if words else get_duration(vpath), "clips": clips_out, "status": "completed"}
    logger.info(f"Pipeline completed successfully. Rendered {len(clips_out)} clips.")
    update_job(100, "Complete")
    return result

async def run_youtube_transcript_first_pipeline(url: str, n: int, base: str, job_id: str = None) -> dict:
    """Fast path for captioned YouTube videos: score captions first, then download only selected windows."""
    def update_job(prog: int, step: str):
        if job_id:
            push_job_update(job_id, prog, step)

    update_job(8, "Fetching YouTube captions before downloading media...")
    words = fetch_youtube_transcript_words(url)
    if not words:
        raise Exception("No YouTube captions were available for transcript-first processing.")

    chunks = semantic_chunks(words)
    if not chunks:
        duration = max(30.0, words[-1]["endMs"] / 1000.0)
        chunks = []
        clip_count = max(1, min(n, 8))
        clip_len = min(35.0, max(12.0, duration / clip_count))
        for i in range(clip_count):
            start = i * clip_len
            end = min(start + clip_len, duration)
            clip_words = [w for w in words if start <= (w.get("startMs", 0) / 1000.0) <= end]
            if not clip_words:
                continue
            text = " ".join(w["word"] for w in clip_words)
            chunks.append(Chunk(start=start, end=end, text=text, words=clip_words, score=80, viable=True))
    if not chunks:
        raise Exception("Could not form caption-based clip segments.")

    update_job(18, "Scoring caption segments for viral moments...")
    try:
        ai_analysis = orchestrate_multi_ai_pipeline(chunks, n)
    except Exception as ae:
        logger.warning(f"Caption-first AI clip analysis unavailable, using heuristic scoring: {ae}")
        ai_analysis = []

    chosen_chunks = []
    if ai_analysis:
        for la in ai_analysis:
            cid = la.get("chunk_id", 0)
            if 0 <= cid < len(chunks):
                c = chunks[cid]
                c.score = la.get("viralScore", 85)
                c.hook = la.get("hookType", "General")
                c.reasons = [la.get("viralReason", "High-engagement viral hook")]
                c.broll_query = la.get("brollQuery", "")
                chosen_chunks.append((c, la.get("title", c.title())))

    if len(chosen_chunks) < n:
        scored = [score(c) for c in chunks]
        heuristic_chosen = [(c, c.title()) for c in select(scored, n)]
        for hc, htitle in heuristic_chosen:
            if len(chosen_chunks) >= n:
                break
            if not any(cc[0].text == hc.text for cc in chosen_chunks):
                chosen_chunks.append((hc, htitle))

    chosen_chunks = fill_requested_chunks(chosen_chunks, "", n, candidates=chunks)

    if not chosen_chunks:
        raise Exception("No viable caption segments selected.")

    clips_out = [None] * len(chosen_chunks)

    def process_youtube_clip(i, chunk, title_text):
        section_start = max(0.0, chunk.start - 2.0)
        section_end = chunk.end + 2.0
        section_path = download_youtube_section(url, RAW_UPLOADS_DIR, section_start, section_end, i, job_id)

        adjusted_words = []
        for w in chunk.words:
            adjusted_words.append({
                "word": w["word"],
                "startMs": max(0, int(w["startMs"] - (section_start * 1000))),
                "endMs": max(80, int(w["endMs"] - (section_start * 1000))),
            })

    update_job(50, "Analysis Complete. Awaiting User Edits...")
    clips_out = []
    for i, (chunk, title_text) in enumerate(chosen_chunks):
        off = chunk.words[0]["startMs"] if chunk.words else 0
        captions = [{"word": w["word"], "startMs": w["startMs"] - off, "endMs": w["endMs"] - off} for w in chunk.words]
        clips_out.append({
            "id": i,
            "title": title_text,
            "startSec": int(chunk.start),
            "endSec": int(chunk.end),
            "viralScore": chunk.score or 85,
            "viralReason": chunk.reasons[0] if chunk.reasons else "High-engagement caption segment",
            "captions": captions,
            "hookType": chunk.hook,
            "durationSec": round(chunk.duration, 1),
            "vpath": url # Since it's a URL, we pass the URL so the render job knows to download the section
        })

    clips_out = [c for c in clips_out if c is not None]

    return {"url": url, "duration": words[-1]["endMs"] / 1000.0 if words else 0, "clips": clips_out, "status": "needs_review"}


def execute_url_job_bg(job_id: str, url: str, n: int, base: str):
    try:
        if is_youtube_url(url):
            try:
                import asyncio
                loop = asyncio.new_event_loop()
                asyncio.set_event_loop(loop)
                res = loop.run_until_complete(run_youtube_transcript_first_pipeline(url, n, base, job_id))
                push_job_update(job_id, progress=100, current_step="Complete", status="completed", result=res)
                return
            except Exception as fast_err:
                logger.warning(f"Transcript-first YouTube pipeline failed; trying bounded section fallback: {fast_err}")
                push_job_update(job_id, progress=6, current_step="YouTube captions are blocked; trying a short media section instead...")

            try:
                section_path = download_youtube_section(url, RAW_UPLOADS_DIR, 0.0, 90.0, 0, job_id)
                execute_job_bg(job_id, section_path, url, n, base)
                return
            except Exception as section_err:
                logger.warning(f"Bounded YouTube section fallback failed: {section_err}")
                if os.getenv("RAPIDAPI_KEY"):
                    push_job_update(job_id, progress=8, current_step="Using configured YouTube ingestion provider...")
                    vpath = download_video_ingest(url, RAW_UPLOADS_DIR, job_id)
                    execute_job_bg(job_id, vpath, url, n, base)
                    return
                raise Exception("YouTube link import is not configured for this cloud server. Upload the video file directly to generate clips reliably.")

        vpath = download_video_ingest(url, RAW_UPLOADS_DIR, job_id)
        execute_job_bg(job_id, vpath, url, n, base)
    except Exception as e:
        logger.error(f"URL job {job_id} failed: {e}")
        push_job_update(job_id, progress=0, current_step="Failed", status="failed", error=str(e))

def execute_render_job_bg(job_id: str, url: str, clips: List[dict], base: str):
    try:
        import asyncio
        loop = asyncio.new_event_loop()
        asyncio.set_event_loop(loop)

        is_yt = is_youtube_url(url)
        vpath = url if is_yt else url

        def update_job(prog: int, step: str):
            push_job_update(job_id, prog, step)

        update_job(60, "FFmpeg 1080p HD Safe Crop & Subtitle Transcoding...")
        clips_out = [None] * len(clips)

        def process_clip(i, clip):
            fname = f"clip_{uuid.uuid4().hex[:8]}_{i}.mp4"
            fpath = os.path.join(CLIPS_DIR, fname)
            try:
                if is_yt:
                    section_start = max(0.0, float(clip['startSec']) - 2.0)
                    section_end = float(clip['endSec']) + 2.0
                    sec_path = download_youtube_section(url, RAW_UPLOADS_DIR, section_start, section_end, i)
                    adj_start = float(clip['startSec']) - section_start
                    adj_end = float(clip['endSec']) - section_start

                    w_adjusted = []
                    for w in clip['captions']:
                        w_copy = w.copy()
                        w_copy["startMs"] = w["startMs"]
                        w_copy["endMs"] = w["endMs"]
                        w_adjusted.append(w_copy)

                    clip_url = transcode_and_upload(sec_path, adj_start, adj_end, fpath, words=w_adjusted, burn_captions=True)
                else:
                    clip_url = transcode_and_upload(vpath, float(clip['startSec']), float(clip['endSec']), fpath, words=clip['captions'], burn_captions=True)

                if clip_url.startswith("/clips/"):
                    clip_url = f"{base}{clip_url}"
                clip['clip_url'] = clip_url
                clip['clipUrl'] = clip_url
                return i, clip
            except Exception as e:
                logger.error(f"Failed to transcode chunk {i}: {e}")
                return i, None

        with concurrent.futures.ThreadPoolExecutor(max_workers=render_worker_count(len(clips))) as executor:
            futures = {executor.submit(process_clip, i, c): i for i, c in enumerate(clips)}
            for future in concurrent.futures.as_completed(futures):
                idx, res_data = future.result()
                if res_data:
                    clips_out[idx] = res_data

        clips_out = [c for c in clips_out if c is not None]
        if not clips_out:
            raise Exception("No clips could be rendered into MP4 output.")

        if modal_volume:
            try:
                modal_volume.commit()
                logger.info("Committed modal_volume after all clips transcoded.")
            except Exception as ve:
                logger.warning(f"Modal volume commit note in render job: {ve}")

        res = {"url": url, "duration": 0, "clips": clips_out, "status": "completed"}
        push_job_update(job_id, progress=100, current_step="Complete", status="completed", result=res)
    except Exception as e:
        logger.error(f"Render job {job_id} failed: {e}")
        push_job_update(job_id, progress=0, current_step="Failed", status="failed", error=str(e))

