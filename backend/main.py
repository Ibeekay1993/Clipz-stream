class Hook(str, Enum):
    SECRET = "Secret"; REVELATION = "Revelation"; MONEY = "Money"; WARNING = "Warning"
    CURIOSITY = "Curiosity"; STORY = "Story"; TUTORIAL = "Tutorial"; CONTRARIAN = "Contrarian"
    EMOTIONAL = "Emotional"; RETENTION = "Retention"; GENERAL = "General"

@dataclass
class Chunk:
    start: float; end: float; text: str; words: List[dict]; score: int = 0
    hook: str = "General"; reasons: List[str] = field(default_factory=list); viable: bool = False
    broll_query: str = ""
    @property
    def duration(self): return self.end - self.start
    def title(self) -> str:
        raw = " ".join(w["word"] for w in self.words[:6])
        return re.sub(r"[^\w\s]", "", raw).strip().capitalize()


def get_duration(video_path: str) -> float:
    """Return video duration in seconds using ffprobe, or 0 when probing fails."""
    try:
        res = subprocess.run(
            [
                resolve_media_binary("FFPROBE_BINARY", "ffprobe"), "-v", "error", "-show_entries", "format=duration",
                "-of", "default=noprint_wrappers=1:nokey=1", video_path
            ],
            check=True,
            capture_output=True,
            text=True,
            timeout=30,
        )
        return float((res.stdout or "0").strip() or 0)
    except Exception as e:
        logger.warning(f"Could not probe video duration for {video_path}: {e}")
        return 0.0

def validate_rendered_mp4(path: str, expected_min_duration: float = 0.5) -> None:
    if not os.path.exists(path):
        raise Exception("Rendered MP4 was not created")
    size = os.path.getsize(path)
    if size <= 1024:
        raise Exception(f"Rendered MP4 is too small ({size} bytes)")
    with open(path, "rb") as f:
        header = f.read(32)
    if b"ftyp" not in header:
        raise Exception("Rendered file does not look like an MP4")

    ffprobe_bin = os.getenv("FFPROBE_BINARY") or shutil.which("ffprobe")
    if not ffprobe_bin:
        logger.warning("ffprobe is unavailable; using basic MP4 validation only.")
        return

    res = subprocess.run(
        [
            ffprobe_bin, "-v", "error",
            "-select_streams", "v:0",
            "-show_entries", "stream=codec_type,width,height:format=duration",
            "-of", "json", path,
        ],
        check=True,
        capture_output=True,
        text=True,
        timeout=30,
    )
    probe = json.loads(res.stdout or "{}")
    streams = probe.get("streams") or []
    if not streams:
        raise Exception("Rendered MP4 has no video stream")
    width = int(streams[0].get("width") or 0)
    height = int(streams[0].get("height") or 0)
    duration = float((probe.get("format") or {}).get("duration") or 0)
    if width <= 0 or height <= 0:
        raise Exception("Rendered MP4 has invalid dimensions")
    if duration < expected_min_duration:
        raise Exception(f"Rendered MP4 duration is invalid ({duration:.2f}s)")

