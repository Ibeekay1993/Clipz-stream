def build_uniform_chunks(video_path: str, max_clips: int) -> List[Chunk]:
    """Last-resort segmentation so uploads still produce downloadable clips."""
    duration = get_duration(video_path) or 60.0
    clip_count = max(1, min(max_clips, 8))
    min_len = 5.0 if duration >= clip_count * 5.0 else max(2.0, duration / clip_count)
    clip_len = min(30.0, max(min_len, duration / clip_count))
    chunks: List[Chunk] = []
    start = 0.0
    while start < duration and len(chunks) < clip_count:
        end = min(start + clip_len, duration)
        if end - start < 5.0:
            break
        label = f"Auto fallback segment {len(chunks) + 1}"
        chunks.append(
            Chunk(
                start=start,
                end=end,
                text=label,
                words=[{"word": label, "startMs": int(start * 1000), "endMs": int(end * 1000)}],
                score=max(70, 86 - (len(chunks) * 3)),
                hook="General",
                reasons=["Generated from timed fallback because transcript AI was unavailable."],
                viable=True,
            )
        )
        start = end
    return chunks
def transcribe(video_path: str) -> List[dict]:
    # 1. Extract audio
    audio_path = video_path + ".mp3"
    subprocess.run([resolve_media_binary("FFMPEG_BINARY", "ffmpeg"), "-y", "-i", video_path, "-vn", "-c:a", "libmp3lame", "-q:a", "5", audio_path], check=True, capture_output=True)

    # 2. Call Groq with native word-level timestamps
    client = Groq(api_key=os.getenv("GROQ_API_KEY"))
    with open(audio_path, "rb") as f:
        resp = client.audio.transcriptions.create(
            file=("audio.mp3", f),
            model="whisper-large-v3",
            response_format="verbose_json",
            timestamp_granularities=["word"]
        )
    if os.path.exists(audio_path):
        os.remove(audio_path)

    # 3. Parse word-level timestamps directly from Groq if available
    out = []
    data = resp.model_dump() if hasattr(resp, "model_dump") else (resp if isinstance(resp, dict) else {})

    top_words = data.get("words", [])
    if top_words:
        for w in top_words:
            w_text = w.get("word", "").strip()
            if w_text:
                out.append({
                    "word": w_text,
                    "startMs": int(w.get("start", 0.0) * 1000),
                    "endMs": int(w.get("end", 0.0) * 1000)
                })
    else:
        for seg in data.get("segments", []):
            seg_words = seg.get("words", [])
            if seg_words:
                for w in seg_words:
                    w_text = w.get("word", "").strip()
                    if w_text:
                        out.append({
                            "word": w_text,
                            "startMs": int(w.get("start", 0.0) * 1000),
                            "endMs": int(w.get("end", 0.0) * 1000)
                        })
            else:
                # Fallback to even split if no word array returned
                text = seg.get("text", "").strip()
                start = seg.get("start", 0.0)
                end = seg.get("end", 0.0)
                words = text.split()
                if not words: continue
                duration_per_word = (end - start) / len(words)
                for i, w in enumerate(words):
                    w_start = start + (i * duration_per_word)
                    w_end = w_start + duration_per_word
                    out.append({"word": w, "startMs": int(w_start * 1000), "endMs": int(w_end * 1000)})
    return out

def semantic_chunks(words: List[dict], max_gap_ms: int = 1800, min_words: int = 10, max_dur_ms: int = 90_000) -> List[Chunk]:
    if not words: return []
    SHIFTS = {"however","but","moving on","next","now","speaking of","anyway","alright","so anyway"}
    chunks: List[Chunk] = []; buf: List[dict] = []; c_start = words[0]["startMs"]; last_end = words[0]["endMs"]
    def flush():
        if len(buf) >= min_words:
            chunks.append(Chunk(start=buf[0]["startMs"]/1000, end=buf[-1]["endMs"]/1000, text=" ".join(w["word"] for w in buf), words=list(buf)))
    for w in words:
        gap = w["startMs"] - last_end; dur = w["startMs"] - c_start; wl = w["word"].lower().strip(".,!?")
        if ((gap > max_gap_ms or (len(buf) > 6 and buf[-1]["word"].endswith((".", "!", "?"))) or wl in SHIFTS or dur > max_dur_ms) and len(buf) >= min_words):
            flush(); buf = [w]; c_start = w["startMs"]
        else: buf.append(w)
        last_end = w["endMs"]
    flush()
    return chunks

def score(c: Chunk) -> Chunk:
    tl = c.text.lower(); dur = c.duration; pts = 70; reasons = ["High-retention speech hook"]; hook = Hook.GENERAL
    if not (5 <= dur <= 90):
        c.score = 0; c.viable = False; return c

    T1 = [(r"nobody (talks about|tells you)", Hook.SECRET, 25), (r"the (real|hidden) truth", Hook.REVELATION, 23)]
    for pat, h, p in T1:
        if re.search(pat, tl): pts += p; hook = h; reasons.append(f"Strong hook - {h.value}"); break

    c.score = min(99, max(50, pts)); c.hook = hook.value; c.reasons = reasons; c.viable = True
    return c

def select(scored: List[Chunk], n: int) -> List[Chunk]:
    pool = sorted([c for c in scored if c.viable], key=lambda x: -x.score)
    if not pool: pool = sorted(scored, key=lambda x: -x.score)
    sel: List[Chunk] = []; used: List[tuple] = []
    for c in pool:
        if len(sel) >= n: break
        # Avoid duplicate overlapping clips while allowing adjacent requested clips.
        if any(max(c.start, s) < min(c.end, e) for s, e in used): continue
        sel.append(c); used.append((c.start, c.end))
    sel.sort(key=lambda x: x.start)
    return sel

def fill_requested_chunks(chosen: List[Tuple[Chunk, str]], video_path: str, n: int, candidates: List[Chunk] = None) -> List[Tuple[Chunk, str]]:
    if len(chosen) >= n:
        return chosen[:n]
    existing = [(c.start, c.end) for c, _ in chosen]
    fallback_pool = candidates or build_uniform_chunks(video_path, n)
    for fallback in fallback_pool:
        if len(chosen) >= n:
            break
        overlaps = any(max(fallback.start, s) < min(fallback.end, e) for s, e in existing)
        if overlaps:
            continue
        chosen.append((fallback, fallback.title()))
        existing.append((fallback.start, fallback.end))
    if len(chosen) < n:
        logger.warning(f"Requested {n} clips but only {len(chosen)} non-overlapping clips could be selected.")
    return chosen

