def download_video_ingest(url: str, out_dir: str, job_id: str = None) -> str:
    out_file = os.path.join(out_dir, f"video_{uuid.uuid4().hex[:8]}.mp4")

    vid_match = re.search(r'(?:v=|\/)([0-9A-Za-z_-]{11})', url)
    if not vid_match:
        raise Exception("Could not parse YouTube video ID from URL")

    v_id = vid_match.group(1)

    rapidapi_key = os.getenv("RAPIDAPI_KEY")
    if not rapidapi_key:
        raise Exception("RAPIDAPI_KEY is missing from environment. Please add it to Modal Secrets.")

    headers = {
        'x-rapidapi-host': 'cloud-api-hub-youtube-downloader.p.rapidapi.com',
        'x-rapidapi-key': rapidapi_key
    }

    if job_id: push_job_update(job_id, progress=5, current_step="Connecting to high-speed ingest network...")

    api_url = f"https://cloud-api-hub-youtube-downloader.p.rapidapi.com/download?id={v_id}"
    logger.info(f"Fetching video info from API for {v_id}")
    req = requests.get(api_url, headers=headers, timeout=20)

    if req.status_code != 200 or (isinstance(req.json(), dict) and 'error' in req.json()):
        raise Exception("Failed to fetch video stream from RapidAPI. Please use 'Upload Video File' instead.")

    data = req.json()
    formats = data if isinstance(data, list) else data.get('formats', [])
    combined = [f for f in formats if str(f.get('acodec')) != 'none' and str(f.get('vcodec')) != 'none']

    if not combined:
        raise Exception("No combined audio/video streams found. Please use 'Upload Video File' instead.")

    combined.sort(key=lambda x: int(x.get('height') or 0), reverse=True)
    best_stream = combined[0]
    stream_url = best_stream.get('url')

    if not stream_url:
        raise Exception("Stream URL was empty from API.")

    if job_id: push_job_update(job_id, progress=10, current_step=f"Downloading high-resolution source video ({best_stream.get('height')}p)...")
    logger.info(f"Downloading {best_stream.get('height')}p stream...")

    stream_resp = requests.get(stream_url, stream=True, timeout=30)
    if stream_resp.status_code == 200:
        with open(out_file, "wb") as f_out:
            for chunk in stream_resp.iter_content(chunk_size=1024*1024):
                if chunk: f_out.write(chunk)
        if os.path.getsize(out_file) > 100_000:
            if job_id: push_job_update(job_id, progress=20, current_step="Video ingestion completed successfully.")
            return out_file

    raise Exception(f"Ingestion failed for {url}: Could not download media streams. Please use 'Upload Video File' instead.")

def is_youtube_url(url: str) -> bool:
    return "youtube.com" in url or "youtu.be" in url


def extract_youtube_id(url: str) -> Optional[str]:
    match = re.search(r'(?:v=|youtu\.be/|/shorts/|/embed/)([0-9A-Za-z_-]{11})', url)
    return match.group(1) if match else None


def fetch_youtube_transcript_words(url_or_id: str) -> List[dict]:
    """Fetch YouTube captions as approximate word timestamps without downloading media."""
    video_id = url_or_id if re.fullmatch(r"[0-9A-Za-z_-]{11}", url_or_id) else extract_youtube_id(url_or_id)
    if not video_id:
        return []

    try:
        from youtube_transcript_api import YouTubeTranscriptApi

        api = YouTubeTranscriptApi()
        transcript = api.fetch(video_id)
        words: List[dict] = []

        for item in transcript:
            if isinstance(item, dict):
                start = float(item.get("start", 0.0) or 0.0)
                duration = float(item.get("duration", 2.0) or 2.0)
                text = str(item.get("text", "") or "")
            else:
                start = float(getattr(item, "start", 0.0) or 0.0)
                duration = float(getattr(item, "duration", 2.0) or 2.0)
                text = str(getattr(item, "text", "") or "")

            parts = [p for p in re.split(r"\s+", text.replace("\n", " ").strip()) if p]
            if not parts:
                continue

            start_ms = int(start * 1000)
            duration_ms = max(100, int(duration * 1000))
            per_word = max(80, duration_ms // len(parts))

            for idx, word in enumerate(parts):
                word_start = start_ms + (idx * per_word)
                words.append({"word": word, "startMs": word_start, "endMs": word_start + per_word})

        return words
    except Exception as e:
        logger.warning(f"YouTubeTranscriptApi transcript fetch failed for {video_id}: {e}")
        return []


def download_youtube_section(url: str, out_dir: str, start: float, end: float, index: int, job_id: str = None) -> str:
    """Download only the selected YouTube time window to avoid full podcast downloads."""
    os.makedirs(out_dir, exist_ok=True)
    section_start = max(0.0, start)
    section_end = max(section_start + 3.0, end)
    out_file = os.path.join(out_dir, f"yt_section_{uuid.uuid4().hex[:8]}_{index}.mp4")
    cookiefile = _cookiefile_path()
    po_token = os.getenv("YTDLP_PO_TOKEN")
    proxy = os.getenv("YTDLP_PROXY")
    yt_args = {"player_client": ["android_vr", "android", "mweb"]}
    if po_token:
        yt_args["po_token"] = [po_token]

    def _section_progress_hook(d):
        if d.get("status") == "downloading" and job_id:
            total_b = d.get("total_bytes") or d.get("total_bytes_estimate") or 0
            downloaded_b = d.get("downloaded_bytes") or 0
            if total_b > 0:
                pct = int((downloaded_b / total_b) * 100)
                push_job_update(
                    job_id,
                    progress=35 + min(20, pct // 5),
                    current_step=f"Downloading selected clip window {index + 1} ({pct}%)..."
                )

    ydl_opts = {
        "format": "bestvideo[ext=mp4]+bestaudio[ext=m4a]/best[ext=mp4]/best",
        "merge_output_format": "mp4",
        "final_ext": "mp4",
        "outtmpl": out_file,
        "quiet": True,
        "no_warnings": True,
        "retries": 3,
        "socket_timeout": 20,
        "download_ranges": download_range_func(None, [(section_start, section_end)]),
        "force_keyframes_at_cuts": True,
        "progress_hooks": [_section_progress_hook],
        "extractor_args": {"youtube": yt_args},
    }
    if cookiefile:
        ydl_opts["cookiefile"] = cookiefile
    if proxy:
        ydl_opts["proxy"] = proxy

    try:
        with yt_dlp.YoutubeDL(ydl_opts) as ydl:
            ydl.download([url])
    except Exception as section_err:
        logger.warning(f"download_ranges failed ({section_err}), retrying full stream download fallback...")
        ydl_opts.pop("download_ranges", None)
        ydl_opts.pop("force_keyframes_at_cuts", None)
        try:
            with yt_dlp.YoutubeDL(ydl_opts) as ydl:
                ydl.download([url])
        except Exception as e2:
            logger.warning(f"Full stream retry failed: {e2}")

    if not os.path.exists(out_file) or os.path.getsize(out_file) < 50_000:
        logger.info("Attempting Cobalt API fallback for section download...")
        try:
            headers = {
                "Accept": "application/json",
                "Content-Type": "application/json",
                "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64)"
            }
            payload = {"url": url, "vCodec": "h264", "videoQuality": "1080"}
            resp = requests.post("https://api.cobalt.tools/api/json", json=payload, headers=headers, timeout=15)
            if resp.status_code == 200:
                data = resp.json()
                dl_url = data.get("url")
                if dl_url:
                    dl_resp = requests.get(dl_url, headers={"User-Agent": headers["User-Agent"]}, stream=True, timeout=60)
                    if dl_resp.status_code == 200:
                        with open(out_file, "wb") as f_out:
                            for chunk in dl_resp.iter_content(chunk_size=1024*1024):
                                if chunk: f_out.write(chunk)
                        if os.path.exists(out_file) and os.path.getsize(out_file) > 50_000:
                            logger.info(f"Cobalt API fallback succeeded for section: {out_file}")
                            return out_file
        except Exception as ce:
            logger.warning(f"Cobalt API fallback note for section: {ce}")

        raise Exception(f"Failed to fetch video stream. YouTube has temporarily blocked our server. Please use 'Upload Video File' instead.")

    return out_file

